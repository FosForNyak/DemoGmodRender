// =============================================================================
//  audio_mute.hpp — вимкнення звуку гри в мікшері гучності Windows на час рендеру.
//
//  Під час рендеру гра грає звук у "рендерному" темпі (пришвидшено) — слухати
//  це неприємно. У відео звук від цього не зміниться: гра пише його у WAV
//  окремо, до мікшера Windows.
//
//  Увага: Windows запам'ятовує гучність кожної програми, тож вимкнений звук
//  лишився б вимкненим і наступного разу. Тому програма обов'язково вмикає
//  його назад, а якщо гра впала раніше — робить це під час наступного запуску
//  гри (позначка в папці програми).
// =============================================================================
#pragma once

#include <cstdint>

namespace gmdr::game {

// Вимкнути/увімкнути звук усіх аудіосесій процесу pid (на всіх пристроях виводу).
// Повертає кількість змінених сесій (0 — у процесу ще немає звуку).
int set_process_audio_mute(uint32_t pid, bool mute);

// Позначка "звук GMod вимкнено нами" (для відновлення після збою).
void mark_game_audio_muted(bool muted);
bool game_audio_mute_pending();

} // namespace gmdr::game
